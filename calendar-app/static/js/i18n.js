let LANG = "zh";

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) || I18N.zh[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, v);
    }
  }
  return s;
}

function setLanguage(lang) {
  LANG = lang === "en" ? "en" : "zh";
  document.documentElement.lang = LANG;
  // data-i18n static texts
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  const langLabel = document.getElementById("more-lang-label");
  if (langLabel) {
    langLabel.textContent = t("menu_lang") + "：" + (LANG === "zh" ? "中文" : "English");
  }
  // re-render dynamic bits
  if (window.CalendarApp) window.CalendarApp.refreshDynamic();
}

function fmtDate(d, opts) {
  return new Intl.DateTimeFormat(LANG === "zh" ? "zh-CN" : "en-US", opts || {
    year: "numeric", month: "long", day: "numeric", weekday: "long",
  }).format(d);
}
